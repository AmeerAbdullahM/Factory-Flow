package com.factoryflow.inventory;

import com.factoryflow.materials.PackagingMaterial;
import com.factoryflow.materials.RawMaterial;
import com.factoryflow.products.Product;
import jakarta.persistence.*;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * Entity mapping to the inventory_balances table.
 * Holds the current quantity on hand and the weighted-average cost for every
 * tracked item (raw material, packaging material, or finished product).
 *
 * <p>Only one of {@code rawMaterial}, {@code packagingMaterial}, or {@code product}
 * will be non-null for a given row; {@code itemType} discriminates which one.</p>
 */
@Entity
@Table(name = "inventory_balances")
public class InventoryBalance {

    /** Primary key – UUID generated by the application. */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", updatable = false, nullable = false)
    private UUID id;

    /**
     * Discriminator: "RAW_MATERIAL", "PACKAGING_MATERIAL", or "PRODUCT".
     * Determines which FK column is populated.
     */
    @Column(name = "item_type", nullable = false, length = 50)
    private String itemType;

    /** Raw material this balance row tracks (null unless itemType = RAW_MATERIAL). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "raw_material_id", nullable = true)
    private RawMaterial rawMaterial;

    /** Packaging material this balance row tracks (null unless itemType = PACKAGING_MATERIAL). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "packaging_material_id", nullable = true)
    private PackagingMaterial packagingMaterial;

    /** Finished product this balance row tracks (null unless itemType = PRODUCT). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "product_id", nullable = true)
    private Product product;

    /**
     * Current quantity on hand.
     * Updated atomically by {@code InventoryService} inside a transaction.
     */
    @Column(name = "current_quantity", nullable = false, precision = 15, scale = 4)
    private BigDecimal currentQuantity = BigDecimal.ZERO;

    /**
     * Weighted-average cost per unit.
     * Recalculated on each purchase receipt using the standard WAC formula.
     */
    @Column(name = "weighted_avg_cost", nullable = false, precision = 15, scale = 6)
    private BigDecimal weightedAvgCost = BigDecimal.ZERO;

    /**
     * Total inventory value = currentQuantity × weightedAvgCost.
     * Kept in sync by the inventory service so reports don't need to recompute it.
     */
    @Column(name = "total_value", nullable = false, precision = 15, scale = 2)
    private BigDecimal totalValue = BigDecimal.ZERO;

    /** Timestamp of the last balance update. Set by the inventory service on each write. */
    @Column(name = "last_updated", nullable = true)
    private Instant lastUpdated;

    public UUID getId() { return id; }
    public void setId(UUID id) { this.id = id; }
    public String getItemType() { return itemType; }
    public void setItemType(String itemType) { this.itemType = itemType; }
    public RawMaterial getRawMaterial() { return rawMaterial; }
    public void setRawMaterial(RawMaterial rawMaterial) { this.rawMaterial = rawMaterial; }
    public PackagingMaterial getPackagingMaterial() { return packagingMaterial; }
    public void setPackagingMaterial(PackagingMaterial packagingMaterial) { this.packagingMaterial = packagingMaterial; }
    public Product getProduct() { return product; }
    public void setProduct(Product product) { this.product = product; }
    public BigDecimal getCurrentQuantity() { return currentQuantity; }
    public void setCurrentQuantity(BigDecimal currentQuantity) { this.currentQuantity = currentQuantity; }
    public BigDecimal getWeightedAvgCost() { return weightedAvgCost; }
    public void setWeightedAvgCost(BigDecimal weightedAvgCost) { this.weightedAvgCost = weightedAvgCost; }
    public BigDecimal getTotalValue() { return totalValue; }
    public void setTotalValue(BigDecimal totalValue) { this.totalValue = totalValue; }
    public Instant getLastUpdated() { return lastUpdated; }
    public void setLastUpdated(Instant lastUpdated) { this.lastUpdated = lastUpdated; }
}
