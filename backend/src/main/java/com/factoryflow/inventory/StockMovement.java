package com.factoryflow.inventory;

import com.factoryflow.users.User;
import com.factoryflow.materials.PackagingMaterial;
import com.factoryflow.materials.RawMaterial;
import com.factoryflow.products.Product;
import jakarta.persistence.*;
import org.hibernate.annotations.CreationTimestamp;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * Entity mapping to the stock_movements table.
 * Records every inbound and outbound stock movement as an immutable ledger entry.
 */
@Entity
@Table(name = "stock_movements")
public class StockMovement {

    /** Primary key – UUID generated by the application. */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", updatable = false, nullable = false)
    private UUID id;

    /** Wall-clock timestamp of when the movement occurred; defaults to NOW(). */
    @Column(name = "movement_date", nullable = false)
    private Instant movementDate = Instant.now();

    /**
     * Discriminator for which item reference is active:
     * "RAW_MATERIAL", "PACKAGING_MATERIAL", or "PRODUCT".
     */
    @Column(name = "item_type", nullable = true, length = 50)
    private String itemType;

    /** Raw-material involved in this movement (nullable). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "raw_material_id", nullable = true)
    private RawMaterial rawMaterial;

    /** Packaging-material involved (nullable). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "packaging_material_id", nullable = true)
    private PackagingMaterial packagingMaterial;

    /** Finished product involved (nullable). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "product_id", nullable = true)
    private Product product;

    /**
     * Type of movement, e.g. PURCHASE_IN, PRODUCTION_IN, PRODUCTION_OUT,
     * SALE_OUT, ADJUSTMENT_IN, ADJUSTMENT_OUT.
     */
    @Column(name = "movement_type", nullable = false, length = 50)
    private String movementType;

    /** Quantity received into stock (null for outbound-only movements). */
    @Column(name = "qty_in", nullable = true, precision = 15, scale = 4)
    private BigDecimal qtyIn;

    /** Quantity issued out of stock (null for inbound-only movements). */
    @Column(name = "qty_out", nullable = true, precision = 15, scale = 4)
    private BigDecimal qtyOut;

    /** Running balance after this movement – maintained by the inventory service. */
    @Column(name = "running_balance", nullable = false, precision = 15, scale = 4)
    private BigDecimal runningBalance;

    /** Cost per unit at the time of this movement. */
    @Column(name = "unit_cost", nullable = true, precision = 15, scale = 4)
    private BigDecimal unitCost;

    /** Total monetary value of this movement (qty * unitCost). */
    @Column(name = "total_value", nullable = true, precision = 15, scale = 2)
    private BigDecimal totalValue;

    /**
     * Type of the source document that triggered this movement,
     * e.g. "PURCHASE", "PRODUCTION_ORDER", "SALES_ORDER".
     */
    @Column(name = "source_document_type", nullable = true, length = 50)
    private String sourceDocumentType;

    /** UUID of the source document record. */
    @Column(name = "source_document_id", nullable = true)
    private UUID sourceDocumentId;

    /** Human-readable reference number cross-linked to the source document. */
    @Column(name = "reference_number", nullable = true, length = 100)
    private String referenceNumber;

    /** Free-text notes for this movement entry. */
    @Column(name = "notes", nullable = true, columnDefinition = "TEXT")
    private String notes;

    /** User who created / recorded this movement. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "created_by", nullable = true)
    private User createdBy;

    /** Audit timestamp set automatically on insert. */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    public UUID getId() { return id; }
    public void setId(UUID id) { this.id = id; }
    public Instant getMovementDate() { return movementDate; }
    public void setMovementDate(Instant movementDate) { this.movementDate = movementDate; }
    public String getItemType() { return itemType; }
    public void setItemType(String itemType) { this.itemType = itemType; }
    public RawMaterial getRawMaterial() { return rawMaterial; }
    public void setRawMaterial(RawMaterial rawMaterial) { this.rawMaterial = rawMaterial; }
    public PackagingMaterial getPackagingMaterial() { return packagingMaterial; }
    public void setPackagingMaterial(PackagingMaterial packagingMaterial) { this.packagingMaterial = packagingMaterial; }
    public Product getProduct() { return product; }
    public void setProduct(Product product) { this.product = product; }
    public String getMovementType() { return movementType; }
    public void setMovementType(String movementType) { this.movementType = movementType; }
    public BigDecimal getQtyIn() { return qtyIn; }
    public void setQtyIn(BigDecimal qtyIn) { this.qtyIn = qtyIn; }
    public BigDecimal getQtyOut() { return qtyOut; }
    public void setQtyOut(BigDecimal qtyOut) { this.qtyOut = qtyOut; }
    public BigDecimal getRunningBalance() { return runningBalance; }
    public void setRunningBalance(BigDecimal runningBalance) { this.runningBalance = runningBalance; }
    public BigDecimal getUnitCost() { return unitCost; }
    public void setUnitCost(BigDecimal unitCost) { this.unitCost = unitCost; }
    public BigDecimal getTotalValue() { return totalValue; }
    public void setTotalValue(BigDecimal totalValue) { this.totalValue = totalValue; }
    public String getSourceDocumentType() { return sourceDocumentType; }
    public void setSourceDocumentType(String sourceDocumentType) { this.sourceDocumentType = sourceDocumentType; }
    public UUID getSourceDocumentId() { return sourceDocumentId; }
    public void setSourceDocumentId(UUID sourceDocumentId) { this.sourceDocumentId = sourceDocumentId; }
    public String getReferenceNumber() { return referenceNumber; }
    public void setReferenceNumber(String referenceNumber) { this.referenceNumber = referenceNumber; }
    public String getNotes() { return notes; }
    public void setNotes(String notes) { this.notes = notes; }
    public User getCreatedBy() { return createdBy; }
    public void setCreatedBy(User createdBy) { this.createdBy = createdBy; }
    public Instant getCreatedAt() { return createdAt; }
    public void setCreatedAt(Instant createdAt) { this.createdAt = createdAt; }
}
